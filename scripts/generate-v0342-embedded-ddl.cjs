const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const source = path.join(root, "contracts", "ai-analysis", "JAA_AI_Analysis_SQLite_Schema_v2.0.0.sql");
const target = path.join(root, "electron", "generated", "aiAnalysisDdlV042.ts");
const expectedSha256 = "1ad8269f4b70eb98571a551bf436cb9a022d681d8f69efef718548cd353cf648";
const bytes = fs.readFileSync(source);
const actualSha256 = crypto.createHash("sha256").update(bytes).digest("hex");

if (actualSha256 !== expectedSha256) {
  throw new Error(`V0342_DDL_HASH_MISMATCH expected=${expectedSha256} actual=${actualSha256}`);
}

const sql = bytes.toString("utf8");
const generated = [
  "// Generated by scripts/generate-v0342-embedded-ddl.cjs. Do not edit manually.",
  `export const AI_ANALYSIS_DDL_VERSION_V042 = ${JSON.stringify("2.0.0")};`,
  `export const AI_ANALYSIS_DDL_SHA256_V042 = ${JSON.stringify(actualSha256)};`,
  `export const AI_ANALYSIS_DDL_V042 = ${JSON.stringify(sql)};`,
  ""
].join("\n");

fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, generated, "utf8");
console.log(JSON.stringify({ status: "PASS", source, target, version: "2.0.0", sha256: actualSha256 }));
