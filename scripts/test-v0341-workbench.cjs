const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = path.resolve(__dirname, "..");
const file = path.join(root, "contracts", "ai-analysis", "Skill_Analysis_Review_Workbench_v1.12.0.html");
const html = fs.readFileSync(file, "utf8");
const scripts = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)].map((match) => match[1]);
assert.ok(scripts.length > 0);
scripts.forEach((source, index) => new vm.Script(source, { filename: `workbench#${index + 1}` }));
assert.match(html, /id="packageFile"/);
assert.match(html, /function immutableOk\(\)/);
assert.match(html, /IMMUTABLE_LAYER_CHANGED/);
assert.match(html, /legacyPending/);
assert.match(html, /legacyAnalyzed/);
assert.match(html, /legacyReview/);
assert.doesNotMatch(html, /\bfetch\s*\(|XMLHttpRequest|new\s+WebSocket|<iframe|<webview/i);
assert.doesNotMatch(html, /<script[^>]+src=|<link[^>]+href=["']https?:/i);
console.log(JSON.stringify({ status: "PASS", version: "0.3.41", emptyFileBootSyntax: true, packageV2Input: true, immutableGate: true, legacyThreeFileGate: true, networkApis: 0, iframe: false }, null, 2));
